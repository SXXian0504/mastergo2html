import assert from 'node:assert/strict'
import test from 'node:test'
import { buildDesignToHtmlSkillPrompt, isDesignToHtmlSkillEnabled } from '../src/workflow/design-to-html-skill.js'

test('design-to-html skill injects workflow-specific compact rules', () => {
  const layoutPrompt = buildDesignToHtmlSkillPrompt('layout', { env: {} })
  assert.match(layoutPrompt, /\[layout\.source-fidelity\]\[hard\]/)
  assert.match(layoutPrompt, /\[responsive\.viewport-contract\]\[hard\]/)
  assert.doesNotMatch(layoutPrompt, /assets\.render-policy/)

  const assetPrompt = buildDesignToHtmlSkillPrompt('assets', { env: {} })
  assert.match(assetPrompt, /\[assets\.real-resource-only\]\[hard\]/)
  assert.match(assetPrompt, /\[assets\.canvas-integrity\]\[hard\]/)
  assert.match(assetPrompt, /真实 width、height、viewBox/)
  assert.match(assetPrompt, /flex:none、max-width:none/)
  assert.match(assetPrompt, /\[layout\.source-fidelity\]\[hard\]/)
  assert.doesNotMatch(assetPrompt, /interaction\.state-matrix/)

  const htmlPrompt = buildDesignToHtmlSkillPrompt('html', { env: {} })
  assert.match(htmlPrompt, /layout\.source-fidelity/)
  assert.match(htmlPrompt, /responsive\.viewport-contract/)
  assert.match(htmlPrompt, /responsive\.header-mobile/)
  assert.match(htmlPrompt, /responsive\.header-intermediate/)
  assert.match(htmlPrompt, /margin-left:auto/)
  assert.match(htmlPrompt, /禁止只流化 Nav/)
  assert.match(htmlPrompt, /Logo 固定为逻辑首项/)
  assert.match(htmlPrompt, /769\/1024\/1280\/1440\/1600/)
  assert.match(htmlPrompt, /断点空洞/)
  assert.match(htmlPrompt, /桌面等分比例/)
  assert.match(htmlPrompt, /覆盖完整等分槽位/)
  assert.match(htmlPrompt, /data-segmented-control/)
  assert.match(htmlPrompt, /data-segmented-active-surface/)
  assert.match(htmlPrompt, /唯一 aria-selected=true/)
  assert.match(htmlPrompt, /不得复用单页像素常量/)
  assert.match(htmlPrompt, /responsive\.footer-wide/)
  assert.match(htmlPrompt, /文字不得进入图标画布或品牌 Logo bbox/)
  assert.match(htmlPrompt, /responsive\.cascade-order/)
  assert.match(htmlPrompt, /responsive\.mobile-card-flow/)
  assert.match(htmlPrompt, /页面只保留 html\/body 一个纵向滚动根/)
  assert.match(htmlPrompt, /overflow-x:hidden/)
  assert.match(htmlPrompt, /禁止徽标继续 absolute 覆盖标题首行/)
  assert.match(htmlPrompt, /相邻 bbox 不相交/)
  assert.match(htmlPrompt, /mastergo2html\.responsive-contract\.v1/)
  assert.match(htmlPrompt, /390\/768\/1280\/1920\/2560/)
  assert.match(htmlPrompt, /interaction\.state-matrix/)
  assert.match(htmlPrompt, /visual\.compact-surface/)
  assert.match(htmlPrompt, /禁止新增 border\/outline/)
  assert.match(htmlPrompt, /圆角 wrapper\/伪元素/)
  assert.match(htmlPrompt, /assets\.real-resource-only/)
  assert.match(htmlPrompt, /output\.local-artifacts/)
  assert.doesNotMatch(htmlPrompt, /output\.agent-direct-files/)
  assert.equal(htmlPrompt.length < 6000, true)
})

test('design-to-html skill can be disabled by env for token comparisons', () => {
  const env = { DESIGN_TO_HTML_SKILL_ENABLED: 'false' }
  assert.equal(isDesignToHtmlSkillEnabled(env), false)
  assert.equal(buildDesignToHtmlSkillPrompt('html', { env }), '')
})

test('app projection excludes web-only responsive rules and includes app interaction rules', () => {
  const prompt = buildDesignToHtmlSkillPrompt('html', { env: {}, target: 'app' })
  assert.doesNotMatch(prompt, /responsive\.viewport-contract/)
  assert.doesNotMatch(prompt, /responsive\.header-mobile/)
  assert.match(prompt, /target\.app-no-hover-dependency/)
  assert.match(prompt, /output\.local-artifacts/)
})
